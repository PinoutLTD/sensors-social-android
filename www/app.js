function ago(ts) {
  const m = Math.round((now() - ts) / 60);
  if (m < 1) return "just now";
  if (m < 60) return m + " min ago";
  const h = Math.round(m / 60);
  return h < 48 ? h + " h ago" : Math.round(h / 24) + " days ago";
}
/** "updated 2 min ago", or "no data for 3 h" once the sensor has been quiet for an hour. */
function freshness(ts) {
  if (now() - ts <= STALE_AFTER) return { stale: false, text: "updated " + ago(ts) };
  const h = Math.round((now() - ts) / 3600);
  return { stale: true, text: "no data for " + (h < 48 ? h + " h" : Math.round(h / 24) + " days") };
}
