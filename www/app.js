/** The map's zones as equal steps, the marker placed inside its step. */
function scaleHTML(key, raw) {
  const zs = ZONES[key]?.zones;
  const z = zoneOf(key, raw);
  if (!zs?.length || !z) return "";
  const lo = z.i ? zs[z.i - 1].max : Math.min(0, raw);
  const hi = zs[z.i].max ?? (lo + (lo || 1));
  const inside = hi > lo ? Math.max(0, Math.min(1, (raw - lo) / (hi - lo))) : 0.5;
  const pos = ((z.i + inside) / zs.length) * 100;
  return `<div><div class="scale">${zs.map((s) => `<span style="background:${s.color}"></span>`).join("")}<i style="left:${pos.toFixed(1)}%"></i></div>
    <div class="scale-labels">${zs.slice(0, -1).map((s, i) => `<span style="left:${(((i + 1) / zs.length) * 100).toFixed(1)}%">${s.max}</span>`).join("")}</div></div>`;
}

