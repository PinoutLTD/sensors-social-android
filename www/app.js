/** Device type the way the map decides it (resolveSensorType): no owner → DIY; then device_model;
 * then what the sensor measures (CO₂ without PM → Insight); otherwise Urban. */
function typeOf(id) {
  const mk = marker(id);
  if (mk && !String(mk.owner || "").trim()) return "diy";
  const m = String(mk?.device_model || "").toLowerCase();
  if (m === "insight" || m === "urban" || m === "diy" || m === "dual") return m;
  const ks = Object.keys(latestOf(seriesCache.get(id + "|24h")?.rows || [])?.data || {});
  if (ks.includes("co2") && !ks.includes("pm25") && !ks.includes("pm10")) return "insight";
  return "urban";
}
