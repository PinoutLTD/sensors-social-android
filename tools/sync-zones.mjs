#!/usr/bin/env node
/**
 * Copies the air-quality scales from the sensors.social map into www/zones.js.
 * The map is the single source of how a reading is rated (decision of the design owner,
 * 11.11.2026): if a threshold or a colour has to change, change it on the map and re-run this.
 *
 *   node tools/sync-zones.mjs [path/to/sensors.social]
 *
 * Reads src/measurements/<key>.js (zones: valueMax, color, label.en; description) and
 * src/assets/styles/variables.css (--measure-* colours).
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const HERE = dirname(fileURLToPath(import.meta.url));
const SITE = resolve(process.argv[2] || join(HERE, "../../sensors.social"));
const KEYS = ["pm25", "pm10", "co2", "noiseavg", "noisemax", "temperature", "humidity", "pressure", "dose_rate_nsv_h"];

const css = readFileSync(join(SITE, "src/assets/styles/variables.css"), "utf8");
const vars = Object.fromEntries([...css.matchAll(/--(measure-[a-z]+):\s*(#[0-9a-fA-F]{3,8})/g)].map((m) => [m[1], m[2]]));
const colour = (c) => String(c).replace(/var\(--(measure-[a-z]+)\)/, (_, v) => vars[v] || c);

const shim = "data:text/javascript," + encodeURIComponent("export const toFixed=(v,n=2)=>Number(v).toFixed(n);");
// only zones and labels are read here, so value helpers can be stand-ins
const aliasShim = "data:text/javascript," + encodeURIComponent("export const measurementValue=(id,v)=>Number(v);export const canonicalMeasurementId=(id)=>id;");
const out = {};
for (const k of KEYS) {
  const src = readFileSync(join(SITE, "src/measurements", k + ".js"), "utf8")
    .replace(/from\s+["']\.\/tools["']/g, `from "${shim}"`)
    .replace(/from\s+["']\.\/aliases["']/g, `from "${aliasShim}"`);
  const m = (await import("data:text/javascript," + encodeURIComponent(src))).default;
  const about = (m.description || []).find((d) => d.tag === "p")?.text?.en || "";
  out[k] = {
    unit: m.unit,
    zones: (m.zones || []).map((z) => ({ max: typeof z.valueMax === "number" ? z.valueMax : null, color: colour(z.color), label: z.label?.en || "" })),
    about,
  };
}
out.nodata = vars["measure-nodata"] || "#d5d3d3";

const commit = (() => { try { return readFileSync(join(SITE, ".git/HEAD"), "utf8").trim(); } catch { return ""; } })();
writeFileSync(join(HERE, "../www/zones.js"),
  `/* Generated by tools/sync-zones.mjs from the sensors.social map (src/measurements, variables.css). Do not edit by hand. */\n` +
  `"use strict";\nconst MAP_ZONES = ${JSON.stringify(out, null, 1)};\n`);
console.log("www/zones.js:", KEYS.map((k) => `${k} ${out[k].zones.length}`).join(", "), commit ? `(${commit})` : "");
